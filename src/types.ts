export type Product = {
  id: string
  /** Игра или платформа, к которой относится товар. */
  game: string
  /** Что именно покупает человек: «660 UC», «Боевой пропуск» и т.д. */
  title: string
  /** Цена в рублях. */
  price: number
  /** Что нужно от покупателя: ID, ник, почта. */
  requires: string
  /** Короткое пояснение под названием. */
  note?: string
  /** Показывать на главной в блоке популярного. */
  popular?: boolean
  /** Слова, по которым товар должен находиться в поиске. */
  keywords?: string[]
}
