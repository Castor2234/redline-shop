/**
 * Кваканье лягушки (easter egg на главной): каждый клик создаёт НОВЫЙ
 * экземпляр Audio, поэтому предыдущие кваки не прерываются — звуки
 * накладываются слоями и игрут до конца.
 *
 * Ограничение: браузер разрешает звук только после жеста пользователя,
 * поэтому зовём исключительно из onClick.
 */
export function playCroak(): void {
  const audio = new Audio('/assets/frog_kwa.ogg')
  audio.volume = 0.8
  void audio.play().catch(() => {
    /* вкладка в фоне / autoplay запрещён — тихо игнорируем */
  })
}